/** REQ-236 (demo M8): server-written send outcome. Not on the request DTOs
 *  — only SendQuote writes it, never a client PUT. */
export interface QuoteDeliveryFields {
  /** The latest send attempt: where it went, or why it didn't. */
  lastDelivery?: QuoteDelivery;
  /** First time any channel actually delivered the quote. */
  deliveredAt?: string;
}

export interface Quote
  extends CreateQuoteDto, NumberedFields, QuoteDeliveryFields {
  /** REQ-039 (NW-52): flagged, never erased — lists exclude it. */
  deletedAt?: string;
  id: string;
  /** Owner. Populated server-side from the auth context — never accept from request body. */
  userId: string;
  createdAt: string;
  updatedAt: string;
}

export type QuoteStage =
  | "draft"
  /** REQ-236: a send was tried and reached nobody — not out for response. */
  | "undelivered"
  | "sent"
  | "opened"
  | "cooling"
  | "stale"
  | "won"
  | "lost";

/**
 * Quote row enriched with the derived stage + engagement signal the /quotes
 * card consumes. Computed by `BuildQuoteCards`; never persisted.
 */
export interface QuoteCard extends Quote {
  stage: QuoteStage;
  daysIn: number;
  opens: number;
  lastOpenAt: string | null;
  sentDays: number | null;
  decidedDays: number | null;
  customerName: string | null;
}

export interface QuoteOpenEntry {
  at: string;
  atRel: string;
  device: "desktop" | "mobile" | "tablet" | "unknown";
  durationMs?: number;
}

export interface QuoteOpensResponse {
  opens: QuoteOpenEntry[];
}

export function parseCreateQuote(input: unknown): CreateQuoteDto {
  const dto = plainToInstance(CreateQuoteDto, input);
  const errors = validateSync(dto);
  if (errors.length) {
    throw new Error(`invalid quote: ${JSON.stringify(errors)}`);
  }
  return dto;
}

export function parseUpdateQuote(input: unknown): UpdateQuoteDto {
  const dto = plainToInstance(UpdateQuoteDto, input);
  const errors = validateSync(dto);
  if (errors.length) {
    throw new Error(`invalid quote patch: ${JSON.stringify(errors)}`);
  }
  return dto;
}
